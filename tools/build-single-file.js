#!/usr/bin/env node
/*
 * Bundles index.html and everything it references into one self-contained
 * pacman.html, so the game can be opened straight off a phone or a USB stick
 * with no server and no separate files.
 *
 *   node tools/build-single-file.js
 */
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const out = path.join(root, 'pacman.html');

const read = (rel) => fs.readFileSync(path.join(root, rel), 'utf8');

/* A literal </script> inside inlined JS would close the tag early. */
function guard(js, rel) {
  if (/<\/script/i.test(js)) {
    throw new Error(rel + ' contains a literal </script> and cannot be inlined as-is');
  }
  return js;
}

let html = read('index.html');

html = html.replace(/[ \t]*<link[^>]*href="([^"]+\.css)"[^>]*>\s*/g, (_, href) =>
  '<style>\n' + read(href).trim() + '\n</style>\n');

html = html.replace(/[ \t]*<script src="([^"]+)"><\/script>\s*/g, (_, src) =>
  '  <script>\n' + guard(read(src), src).trim() + '\n  </script>\n');

const leftovers = html.match(/(?:src|href)="(?!data:|https?:|#)[^"]+"/g);
if (leftovers) throw new Error('unbundled references remain: ' + leftovers.join(', '));

const banner = '<!--\n  PAC-MAN - single-file build. Generated by tools/build-single-file.js;\n' +
               '  edit the sources in js/ and css/, not this file.\n-->\n';
fs.writeFileSync(out, banner + html);

const kb = (fs.statSync(out).size / 1024).toFixed(1);
console.log('wrote ' + path.relative(root, out) + ' (' + kb + ' KB, no external files)');
