/** Builds the L side from the authored R side, optionally half a cycle later. */
function mirrorSides(clip, phase = 0) {
  const out = {};
  for (const name of Object.keys(clip.tracks)) out[name] = clip.tracks[name];
  for (const name of Object.keys(clip.tracks)) {
    const lname = toLeftName(name);
    if (!lname) continue;
    out[lname] = mirrorKeys(clip.tracks[name], phase, clip.duration);
  }
  // Core bones have no mirrored twin, but a phase shifted clip still needs them
  // to line up, which they already do because they are authored full cycle.
  clip.tracks = out;
  return clip;
}

function toLeftName(name) {
  // upperArmR -> upperArmL, fingerR2A -> fingerL2A, thumbRA -> thumbLA
  if (/^(upperArm|lowerArm|hand|upperLeg|lowerLeg|foot|footTip)R$/.test(name)) return name.slice(0, -1) + 'L';
  let m = name.match(/^fingerR(\d)([AB])$/);
  if (m) return `fingerL${m[1]}${m[2]}`;
  m = name.match(/^thumbR([AB])$/);
  if (m) return `thumbL${m[1]}`;
  return null;
}

function mirrorKeys(keys, phase, duration) {
  const shifted = keys.map((k) => [k[0], k[1], -k[2], -k[3]]);
  if (!phase) return shifted;
  const off = phase * duration;
  const moved = shifted.map((k) => {
    let t = k[0] + off;
    if (t >= duration) t -= duration;
    return [t, k[1], k[2], k[3]];
  }).sort((a, b) => a[0] - b[0]);
  // keep the loop closed
  if (moved.length && moved[0][0] > 0) {
    const last = moved[moved.length - 1];
    moved.unshift([0, last[1], last[2], last[3]]);
  }
  const first = moved[0];
  if (moved[moved.length - 1][0] < duration) moved.push([duration, first[1], first[2], first[3]]);
  return moved;
}

/** Full body mirror: swaps every L/R track and flips Y/Z everywhere. */
export function mirrorClip(clip, name) {
  const tracks = {};
  for (const key of Object.keys(clip.tracks)) {
    const target = swapSide(key);
    tracks[target] = clip.tracks[key].map((k) => [k[0], k[1], -k[2], -k[3]]);
  }
  return { ...clip, name, tracks, rootPitch: clip.rootPitch, rootY: clip.rootY };
}

function swapSide(name) {
  if (/^(upperArm|lowerArm|hand|upperLeg|lowerLeg|foot|footTip)[RL]$/.test(name)) {
    return name.endsWith('R') ? name.slice(0, -1) + 'L' : name.slice(0, -1) + 'R';
  }
  let m = name.match(/^finger([RL])(\d)([AB])$/);
  if (m) return `finger${m[1] === 'R' ? 'L' : 'R'}${m[2]}${m[3]}`;
  m = name.match(/^thumb([RL])([AB])$/);
  if (m) return `thumb${m[1] === 'R' ? 'L' : 'R'}${m[2]}`;
  return name;
}

/** Repeats one value across all four fingers of a hand. */
function fingers(side, keysA, keysB) {
  const t = {};
  for (let i = 0; i < 4; i++) {
    t[`finger${side}${i}A`] = keysA;
    t[`finger${side}${i}B`] = keysB;
  }
  t[`thumb${side}A`] = keysA.map((k) => [k[0], k[1] * 0.6, k[2], k[3]]);
  t[`thumb${side}B`] = keysB.map((k) => [k[0], k[1] * 0.6, k[2], k[3]]);
  return t;
}

