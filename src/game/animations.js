/* =============================================================================
   Keyframed animation. Every clip is authored as multi-frame data and sampled
   with a Catmull-Rom style cubic, so the motion is smooth rather than snapping
   between poses.

   Sign conventions (see skeleton.js):
     arms / legs : +X rotation swings the limb FORWARD
     knees       : bend backwards, so their X keys are negative
     elbows      : bend forwards, so their X keys are positive
     spine / head: +X leans BACKWARD, so forward lean is negative
     fingers     : curl towards the palm with NEGATIVE X
     +Y on the spine turns the right shoulder forward
   ========================================================================== */

/* -------------------------------------------------------------------------- */
/*                                  sampling                                  */
/* -------------------------------------------------------------------------- */

function hermite(p0, m0, p1, m1, u) {
  const u2 = u * u, u3 = u2 * u;
  return (2 * u3 - 3 * u2 + 1) * p0 + (u3 - 2 * u2 + u) * m0 +
         (-2 * u3 + 3 * u2) * p1 + (u3 - u2) * m1;
}

/** Cubic sample of a [t, a, b, c] track. `comp` selects 1..3. */
function sampleComponent(keys, t, duration, loop, comp) {
  const n = keys.length;
  if (n === 0) return 0;
  if (n === 1) return keys[0][comp];

  let i = 0;
  while (i < n - 1 && keys[i + 1][0] <= t) i++;
  if (t <= keys[0][0]) {
    if (!loop) return keys[0][comp];
  }
  if (t >= keys[n - 1][0] && !loop) return keys[n - 1][comp];

  const idx = (k) => {
    if (loop) return ((k % n) + n) % n;
    return k < 0 ? 0 : k > n - 1 ? n - 1 : k;
  };
  const timeAt = (k) => {
    if (!loop) return keys[idx(k)][0];
    const wraps = Math.floor(k / n);
    return keys[idx(k)][0] + wraps * duration;
  };

  const i0 = i - 1, i1 = i, i2 = i + 1, i3 = i + 2;
  const t1 = timeAt(i1), t2 = timeAt(i2);
  const h = Math.max(1e-6, t2 - t1);
  const u = Math.min(1, Math.max(0, (t - t1) / h));

  const p0 = keys[idx(i0)][comp], p1 = keys[idx(i1)][comp];
  const p2 = keys[idx(i2)][comp], p3 = keys[idx(i3)][comp];
  const t0 = timeAt(i0), t3 = timeAt(i3);

  const m1 = (p2 - p0) / Math.max(1e-6, t2 - t0) * h;
  const m2 = (p3 - p1) / Math.max(1e-6, t3 - t1) * h;
  return hermite(p1, m1, p2, m2, u);
}

export function sampleTrack(keys, t, duration, loop, out) {
  out.x = sampleComponent(keys, t, duration, loop, 1);
  out.y = sampleComponent(keys, t, duration, loop, 2);
  out.z = sampleComponent(keys, t, duration, loop, 3);
  return out;
}

export function sampleScalar(keys, t, duration, loop) {
  return sampleComponent(keys, t, duration, loop, 1);
}

